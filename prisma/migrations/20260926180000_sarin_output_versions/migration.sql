-- Content belongs to its version's own generating transaction: nothing can be added later.
CREATE OR REPLACE FUNCTION "sarin_assert_version_being_generated"(version_id TEXT) RETURNS void AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM "SarinOutputVersion" WHERE "id" = version_id AND "xmin" = pg_current_xact_id()::xid) THEN
    RAISE EXCEPTION 'Sarin output content can only be written by the transaction that generates its version'
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$ LANGUAGE plpgsql;


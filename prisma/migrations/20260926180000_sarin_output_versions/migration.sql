-- Sarin Blue/White output versions (additive).
--
-- Validation attempts record the validation profile they ran, so an attempt made under an
-- older contract is never taken as proof that newer checks passed. Structured output is
-- stored as immutable versions of plan options and pieces derived from one clean,
-- current validation attempt; the database refuses anything else, refuses content written
-- outside the generating transaction, and verifies every piece against its source row and
-- every stored yield against its own numerator and denominator.

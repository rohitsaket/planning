    RAISE EXCEPTION 'A parsed or quarantined Sarin stone block is immutable'
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF OLD."parseStatus" = 'PENDING' AND NEW."parseStatus" <> 'PENDING' THEN
    NEW."parsedAt" := now();
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


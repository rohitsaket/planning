--
-- Every rejection RAISEs. Nothing here uses a RULE or DO INSTEAD NOTHING, because a write
-- that is silently discarded reports success — the opposite of an integrity control.
-- Row-level triggers do not fire on TRUNCATE, which the isolated test suite relies on.

-- ---------------------------------------------------------------- shared helpers

CREATE OR REPLACE FUNCTION "sarin_reject_mutation"() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is insert-only; % is not permitted', TG_TABLE_NAME, TG_OP
    USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION "sarin_reject_delete"() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% rows are permanent history; DELETE is not permitted', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;


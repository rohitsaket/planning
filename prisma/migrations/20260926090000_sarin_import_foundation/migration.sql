CREATE OR REPLACE FUNCTION "sarin_issue_override_insert_guard"() RETURNS trigger AS $$
DECLARE
  issue_status TEXT;
  issue_blocking BOOLEAN;
  superseded_kind TEXT;
BEGIN
  SELECT "status", "blocking" INTO issue_status, issue_blocking
    FROM "SarinValidationIssue" WHERE "id" = NEW."issueId" FOR SHARE;
  IF issue_status IS NULL OR issue_status NOT IN ('OPEN', 'OVERRIDDEN') THEN
    RAISE EXCEPTION 'Only an OPEN or OVERRIDDEN Sarin validation issue can receive a review decision (issue is %)',
      coalesce(issue_status, 'missing')
      USING ERRCODE = 'check_violation';
  END IF;
  -- Acknowledging is for warnings. It can never be used to wave through a blocking issue.
  IF NEW."kind" = 'ACKNOWLEDGE_WARNING' AND issue_blocking THEN
    RAISE EXCEPTION 'A blocking Sarin validation issue cannot be acknowledged'
      USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."supersedesOverrideId" IS NOT NULL THEN
    SELECT "kind" INTO superseded_kind FROM "SarinIssueOverride" WHERE "id" = NEW."supersedesOverrideId";
    IF NEW."kind" = 'REVOCATION' AND superseded_kind = 'REVOCATION' THEN
      RAISE EXCEPTION 'A revocation cannot be revoked; record a new decision instead'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- A file record without its bytes is not evidence. Checked at commit, so the file row and
-- its content can be written in either order inside one transaction.
CREATE OR REPLACE FUNCTION "sarin_source_file_requires_content"() RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM "SarinSourceFileContent" WHERE "sourceFileId" = NEW."id") THEN
    RAISE EXCEPTION 'SarinSourceFile % was committed without its content', NEW."id"
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;


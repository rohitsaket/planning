-- Sarin import foundation (additive).
--
-- Persistence for the headerless Sarin CSV workflow: immutable source files and rows,
-- stone blocks, validation issues, append-only reviewed overrides and versioned Sarin
-- shape mappings. No existing table is altered; Fantasy ShapeMapping is untouched.
--
-- Part 1 is the DDL Prisma generates from schema.prisma. Part 2 adds the rules Prisma
-- cannot express. Part 3 seeds the confirmed Sarin shape master as a DRAFT set, which no
-- batch can reference until a person with sarin.mapping.manage approves it.
--
-- Reversal: down.sql. Only safe before any real Sarin data exists, because it drops the
-- tables that hold source evidence.


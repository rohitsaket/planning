CREATE OR REPLACE FUNCTION "sarin_shape_mapping_rule_guard"() RETURNS trigger AS $$
DECLARE
  set_status TEXT;
BEGIN
  -- Rules belong to their set's content: they may change only while the set is a DRAFT.
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    SELECT "status" INTO set_status FROM "SarinShapeMappingSet" WHERE "id" = OLD."mappingSetId" FOR SHARE;
    IF set_status IS DISTINCT FROM 'DRAFT' THEN
      RAISE EXCEPTION 'Rules of a % Sarin shape mapping set are immutable', set_status
        USING ERRCODE = 'restrict_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
  END IF;

  SELECT "status" INTO set_status FROM "SarinShapeMappingSet" WHERE "id" = NEW."mappingSetId" FOR SHARE;
  IF set_status IS DISTINCT FROM 'DRAFT' THEN
    RAISE EXCEPTION 'Rules of a % Sarin shape mapping set are immutable', coalesce(set_status, 'missing')
      USING ERRCODE = 'restrict_violation';
  END IF;

  -- Serialize writers of the same raw shape in the same set, so two concurrent inserts
  -- cannot both pass the overlap check below.
  PERFORM pg_advisory_xact_lock(hashtext('sarin-shape-rule:' || NEW."mappingSetId" || ':' || NEW."rawShapeKey"));

  -- A raw shape either has one unconditional rule or only non-overlapping ratio ranges;
  -- it can never resolve to two shapes for the same Ratio.
  IF EXISTS (
    SELECT 1 FROM "SarinShapeMappingRule" o
     WHERE o."mappingSetId" = NEW."mappingSetId"
       AND o."rawShapeKey" = NEW."rawShapeKey"
       AND o."id" <> NEW."id"
       AND (o."conditionKind" = 'NONE' OR NEW."conditionKind" = 'NONE'
            OR (coalesce(o."ratioMin", -1) <= coalesce(NEW."ratioMax", 1000000)
                AND coalesce(NEW."ratioMin", -1) <= coalesce(o."ratioMax", 1000000)))
  ) THEN
    RAISE EXCEPTION 'Sarin shape mapping rule for % overlaps an existing rule in the same set', NEW."rawShapeKey"
      USING ERRCODE = 'exclusion_violation';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


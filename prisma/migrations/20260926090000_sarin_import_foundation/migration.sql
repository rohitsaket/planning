CREATE OR REPLACE FUNCTION "sarin_source_file_content_verify"() RETURNS trigger AS $$
DECLARE
  expected_sha TEXT;
  expected_size INTEGER;
BEGIN
  SELECT "sha256", "byteSize" INTO expected_sha, expected_size
    FROM "SarinSourceFile" WHERE "id" = NEW."sourceFileId";
  IF expected_sha IS NULL THEN
    RAISE EXCEPTION 'SarinSourceFileContent references an unknown source file'
      USING ERRCODE = 'foreign_key_violation';
  END IF;
  -- The stored checksum and size are facts about these exact bytes, not claims.
  IF encode(sha256(NEW."content"), 'hex') <> expected_sha THEN
    RAISE EXCEPTION 'SarinSourceFileContent does not match the recorded SHA-256'
      USING ERRCODE = 'check_violation';
  END IF;
  IF octet_length(NEW."content") <> expected_size THEN
    RAISE EXCEPTION 'SarinSourceFileContent does not match the recorded byte size'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ---------------------------------------------------------------- row interpretations
ALTER TABLE "SarinRowInterpretation"
  ADD CONSTRAINT "SarinRowInterpretation_validationAttempt_check" CHECK ("validationAttempt" > 0),
  ADD CONSTRAINT "SarinRowInterpretation_mappingResult_check"
    CHECK ("mappingResult" IN ('MAPPED', 'CONDITIONALLY_MAPPED', 'UNMAPPED', 'AMBIGUOUS', 'OVERRIDDEN')),
  -- A resolved shape always names the rule that produced it; an unresolved one names neither.
  ADD CONSTRAINT "SarinRowInterpretation_resolution_consistent_check"
    CHECK ((("mappingResult" IN ('MAPPED', 'CONDITIONALLY_MAPPED')) AND "normalizedShape" IS NOT NULL AND "mappingRuleId" IS NOT NULL)
        OR (("mappingResult" IN ('UNMAPPED', 'AMBIGUOUS')) AND "normalizedShape" IS NULL AND "mappingRuleId" IS NULL)
        OR ("mappingResult" = 'OVERRIDDEN' AND "normalizedShape" IS NOT NULL AND "mappingRuleId" IS NULL)),
  ADD CONSTRAINT "SarinRowInterpretation_rawShapeKey_check"
    CHECK ("rawShapeKey" IS NULL OR ("rawShapeKey" = upper(btrim("rawShapeKey")) AND char_length("rawShapeKey") BETWEEN 1 AND 256)),
  ADD CONSTRAINT "SarinRowInterpretation_mapped_has_key_check"
    CHECK ("mappingResult" NOT IN ('MAPPED', 'CONDITIONALLY_MAPPED') OR "rawShapeKey" IS NOT NULL),
  ADD CONSTRAINT "SarinRowInterpretation_metadataJson_check"
    CHECK ("metadataJson" IS NULL
           OR (char_length("metadataJson") <= 2000 AND jsonb_typeof("metadataJson"::jsonb) = 'object'));

CREATE OR REPLACE FUNCTION "sarin_row_interpretation_insert_guard"() RETURNS trigger AS $$
DECLARE
  a_status TEXT;
  a_number INTEGER;
  a_set TEXT;
  r_set TEXT;
  r_key TEXT;
  r_shape TEXT;
BEGIN
  -- Written only by the attempt it belongs to, while that attempt is running.
  SELECT "status", "attemptNumber", "shapeMappingSetId" INTO a_status, a_number, a_set
    FROM "SarinValidationAttempt" WHERE "id" = NEW."attemptId" FOR SHARE;
  IF a_status IS DISTINCT FROM 'RUNNING' OR NEW."validationAttempt" <> a_number OR NEW."shapeMappingSetId" <> a_set THEN
    RAISE EXCEPTION 'A Sarin row interpretation belongs to a running attempt and its mapping set'
      USING ERRCODE = 'check_violation';
  END IF;
  -- The applied rule is a rule of that set, for this raw shape, giving this shape.
  IF NEW."mappingRuleId" IS NOT NULL THEN
    SELECT "mappingSetId", "rawShapeKey", "normalizedShape" INTO r_set, r_key, r_shape
      FROM "SarinShapeMappingRule" WHERE "id" = NEW."mappingRuleId";
    IF r_set IS DISTINCT FROM NEW."shapeMappingSetId" OR r_key IS DISTINCT FROM NEW."rawShapeKey"
       OR r_shape IS DISTINCT FROM NEW."normalizedShape" THEN
      RAISE EXCEPTION 'A Sarin row interpretation must cite the rule that produced its shape'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "sarin_row_interpretation_insert_guard"
  BEFORE INSERT ON "SarinRowInterpretation"
  FOR EACH ROW EXECUTE FUNCTION "sarin_row_interpretation_insert_guard"();

CREATE TRIGGER "sarin_row_interpretation_immutable"
  BEFORE UPDATE OR DELETE ON "SarinRowInterpretation"

-- Sarin validation attempts (additive).
--
-- A validation attempt parses stone identity, forms consecutive stone blocks and resolves
-- shapes through one APPROVED mapping set. Each attempt is recorded in
-- SarinValidationAttempt; each row's shape resolution in SarinRowInterpretation, without
-- copying or changing the immutable source row. Issues gain an ordinal so a finding list
-- has a stable, meaningful order. Mapping sets record their last editor, and the database
-- refuses an approval by the set's creator or last editor.
--
-- Reversal: down.sql.

